"""Bake the overlay's DejaVu Sans Bold distance field (Pillow, NumPy, SciPy required)."""
from pathlib import Path
import hashlib
import numpy as np
from PIL import Image, ImageDraw, ImageFont
from scipy.ndimage import distance_transform_edt

root = Path(__file__).resolve().parents[2]
source = root / 'third_party/fonts/DejaVuSans-Bold.ttf'
expected = 'e6476c1b80502924294eed40894c5b18e06c181444ca953e5334262df9c27724'
if hashlib.sha256(source.read_bytes()).hexdigest() != expected:
    raise ValueError('Unexpected overlay font source')
size, width, height, padding, baseline, supersample = 28, 40, 44, 4, 32, 8
font = ImageFont.truetype(str(source), size)
high_font = ImageFont.truetype(str(source), size * supersample)
advances, atlas = [], []
for code in range(32, 127):
    character = chr(code)
    advances.append(round(font.getlength(character)) + 2)
    image = Image.new('L', (width * supersample, height * supersample))
    ImageDraw.Draw(image).text((padding * supersample, baseline * supersample), character,
                              font=high_font, anchor='ls', fill=255)
    inside = np.asarray(image) >= 128
    if not inside.any():
        atlas.append(np.zeros((height, width), dtype=np.uint8))
        continue
    distance = (distance_transform_edt(inside) - distance_transform_edt(~inside)) / supersample
    distance = distance.reshape(height, supersample, width, supersample).mean(axis=(1, 3))
    atlas.append(np.clip(np.rint(128 + distance * 16), 0, 255).astype(np.uint8))
words = np.frombuffer(np.stack(atlas).tobytes(), dtype='<u4')
lines = [', '.join(f'0x{int(w):08x}u' for w in words[i:i + 8]) for i in range(0, len(words), 8)]
header = '''// Generated by tools/overlay/build-font.py. DejaVu Sans Bold: see LICENSES/DejaVu-fonts.txt.
#pragma once
#include <cstdint>
namespace fsr4runtime {
inline constexpr uint32_t kOverlayFontSize = 28;
inline constexpr uint32_t kOverlayFontWidth = 40;
inline constexpr uint32_t kOverlayFontHeight = 44;
inline constexpr uint32_t kOverlayFontPadding = 4;
inline constexpr uint32_t kOverlayFontAdvances[] = {
    ''' + ', '.join(str(x) for x in advances) + '''
};
inline constexpr uint32_t kOverlayFontPixels[] = {
    ''' + ',\n    '.join(lines) + '\n};\n} // namespace fsr4runtime\n'
(root / 'src/diagnostics/overlay_font.hpp').write_text(header)
print(f'Baked {len(atlas)} glyphs, {words.nbytes} bytes')
